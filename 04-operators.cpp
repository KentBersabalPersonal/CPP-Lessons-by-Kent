
#include <iostream>
using namespace std;

int main() {

  int a = 10;
  int b = 3;

  cout << "\nSum: " << a + b << endl;

  cout << "Difference: " << a - b << endl;

  cout << "Product: " << a * b << endl;

  cout << "Quotient: " << a / b << endl;

  cout << "Remainder: " << a % b << endl;

  return 0;
}

// OUTPUT IS: 

// Sum: 1
// Difference: 7
// Product: 30
// Quotient: 3
// Remainder: 1

